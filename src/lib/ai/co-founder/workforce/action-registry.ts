/**
 * Returns the exact ActionRiskCategory for an action.
 * Returns undefined if the action is unrecognized (triggering fail-closed DENY).
 */
export function getActionRiskCategory(
  actionName: string
): ActionRiskCategory | undefined {
  if (!actionName || typeof actionName !== 'string') return undefined;
  const normalized = actionName.toLowerCase().trim();
  return ACTION_RISK_REGISTRY[normalized];
}
